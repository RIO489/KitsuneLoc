"""Літери, яких немає у шрифті гри, і чим їх підміняти.

У `msgfont.ffu`/`sysfont.ffu` немає гліфів `і І ї Ї є Є ґ Ґ` — гра просто
викидає такі символи з рядка. Додати їх у шрифт новими записами не вийшло:
движок нові діапазони ігнорує. Тому `maryskelter/fontfix.py` перемальовує
вісім латинських літер, які в жодному рядку гри не трапляються, а тут ми
підставляємо їх замість українських уже при записі в гру.

Перекладач пише нормальну українську — підміна невидима і зворотна.
"""

SUBST = {
    'і': 'ì', 'І': 'Ì',
    'ї': 'ò', 'Ї': 'Ò',
    'є': 'ù', 'Є': 'Ù',
    'ґ': 'ã', 'Ґ': 'Ã',
}
# зайнятих слотів у тексті бути не повинно — попередимо перекладача
RESERVED = set(SUBST.values())
# немає ні гліфа, ні прийнятної заміни
NO_GLYPH = set('ō')


def apply(text):
    """Підмінити літери, яких гра не малює."""
    return text.translate(str.maketrans(SUBST)) if text else text


def missing(text):
    """Літери, які зникнуть у грі навіть після підміни."""
    return sorted({c for c in (text or '') if c in NO_GLYPH})
