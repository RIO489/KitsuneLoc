"""Літери, яких немає у шрифті гри, і чим їх підміняти (дані цієї гри).

У `msgfont.ffu`/`sysfont.ffu` немає гліфів `і І ї Ї є Є ґ Ґ` — гра просто
викидає такі символи з рядка. Додати їх у шрифт новими записами не вийшло:
движок нові діапазони ігнорує. Тому шрифт (maryskelter/fontfix.py) малює їх у
вісім латинських літер, які в жодному рядку гри не трапляються, а тут ми
підставляємо їх замість українських уже при записі в гру.

Логіка — спільна для UTF-8-рушіїв (compileheart/scheme.SlotScheme); тут лише дані й
старий API (apply, missing, RESERVED). Перекладач пише нормальну українську —
підміна невидима і зворотна.
"""
from compileheart.scheme import SlotScheme

SUBST = {
    'і': 'ì', 'І': 'Ì',
    'ї': 'ò', 'Ї': 'Ò',
    'є': 'ù', 'Є': 'Ù',
    'ґ': 'ã', 'Ґ': 'Ã',
}
# немає ні гліфа, ні прийнятної заміни
NO_GLYPH = set('ō')

SCHEME = SlotScheme(SUBST, no_glyph=NO_GLYPH)
# зайнятих слотів у тексті бути не повинно — попередимо перекладача
RESERVED = SCHEME.reserved()
apply = SCHEME.apply_text          # підмінити літери, яких гра не малює
missing = SCHEME.bad_chars         # літери, які зникнуть у грі навіть після підміни
