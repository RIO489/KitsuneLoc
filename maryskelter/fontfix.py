# -*- coding: utf-8 -*-
"""Шрифти Mary Skelter Nightmares (msgfont.ffu / sysfont.ffu) — профіль для спільного
compileheart/fontfix.py (алгоритм один на всі ігри рушія).

Особливості цієї гри (перевірено в грі, тому закріплено, а не визначається автоматично):
  - кирилиця в клітинках повної ширини → обрізаємо по чорнилу, відступи 1 px зліва і
    2 px справа (порожніми колонками), як у латиниці;
  - і І ї Ї є Є ґ Ґ немає, а нові діапазони рушій ІГНОРУЄ → малюємо їх у вісім латинських
    літер, яких жоден рядок гри не вживає (SLOT); maryskelter/chars.py підміняє їх у тексті;
  - ї/Ї — з готових ï/Ï шрифту, вусик ґ/Ґ — 5×9 px, дзеркало є/Є — після обрізання.
Відмінність від старого коду (до 2.3): дефіс U+2010 більше не «звужується» випадково —
старий ffu читав кінець діапазону включно й приймав його гліф за «ђ» (U+2010 у тексті гри —
2 рази, лише в англійському оригіналі).
"""
from compileheart import fontfix as _fix
from . import chars

# українська літера -> латинський слот, у який ми малюємо її гліф (дані — maryskelter/chars.py)
SLOT = chars.SUBST
SCHEME = chars.SCHEME      # одна схема на гру: і шрифт, і текст
PROFILE = {'bearings': (1, 2), 'pad_right': True, 'crop_first': True,
           'yi': 'diaeresis', 'ghe': (5, 9), 'slant': 0}


def fix(data):
    """Оригінальний .ffu -> (новий .ffu, звіт {'tightened', 'added', …})."""
    return _fix.fix(data, SCHEME, PROFILE)
